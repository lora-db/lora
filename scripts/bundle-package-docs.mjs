#!/usr/bin/env node
// Bundle a curated, plain-Markdown copy of the loradb.com docs into an npm
// package, so `node_modules/@loradb/<pkg>/docs/` carries the documentation
// for exactly the installed version. Meant for offline use and for coding
// agents that read node_modules.
//
// Usage (from a package directory, or pass it as the first argument):
//   node ../../scripts/bundle-package-docs.mjs [packageDir]
//
// Pages come from the llms.txt manifest
// (apps/loradb.com/plugins/llms-txt/manifest.js), filtered per package
// below. MDX components are rewritten to plain Markdown, links to bundled
// pages become relative file links, and every other link becomes an
// absolute https://loradb.com URL.
//
// Output: <packageDir>/docs/ (gitignored, listed in the package's `files`).
// It is regenerated from scratch on every run.

import { createRequire } from "node:module";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE_DIR = path.join(ROOT, "apps/loradb.com");
const SITE_URL = "https://loradb.com";
const MARKER = "<!-- generated by scripts/bundle-package-docs.mjs -->";

const siteRequire = createRequire(path.join(SITE_DIR, "package.json"));
const matter = siteRequire("gray-matter");
const manifest = siteRequire("./plugins/llms-txt/manifest.js");
const { mdxToMarkdown } = siteRequire("./plugins/llms-txt/mdx-to-markdown.js");
const { resolveDocHref } = siteRequire("./plugins/llms-txt/docs-index.js");

// Pages every engine-facing package gets.
const ENGINE_CORE = [
  "index",
  "why",
  "getting-started/installation",
  "getting-started/tutorial",
  "concepts/*",
  "queries/*",
  "functions/*",
  "data-types/*",
  "cookbook",
  "snapshot",
  "performance",
  "errors",
  "limitations",
  "troubleshooting",
];

const PACKAGES = {
  "@loradb/lora-node": {
    pages: [...ENGINE_CORE, "getting-started/node", "wal"],
  },
  "@loradb/lora-wasm": {
    pages: [...ENGINE_CORE, "getting-started/wasm"],
  },
  "@loradb/lora-graphql": {
    pages: [
      "graphql/*",
      "index",
      "getting-started/node",
      "queries/*",
      "functions/*",
      "data-types/*",
      "errors",
      "limitations",
    ],
  },
};

const packageDir = path.resolve(process.argv[2] || process.cwd());
const pkg = JSON.parse(
  readFileSync(path.join(packageDir, "package.json"), "utf8"),
);
const config = PACKAGES[pkg.name];
if (!config) {
  console.error(`bundle-package-docs: no docs selection for ${pkg.name}`);
  process.exit(1);
}
if (!(pkg.files || []).includes("docs/")) {
  console.error(`bundle-package-docs: add "docs/" to ${pkg.name}'s "files"`);
  process.exit(1);
}

const matches = (slug) =>
  config.pages.some((p) =>
    p.endsWith("/*") ? slug.startsWith(p.slice(0, -1)) : slug === p,
  );

// Manifest order, docs entries only (the blog essays stay online).
const sections = [];
for (const section of manifest.sections) {
  const entries = section.entries
    .filter((e) => e.source.startsWith("docs/"))
    .map((e) => ({
      ...e,
      slug: e.source.replace(/^docs\//, "").replace(/\.mdx?$/, ""),
    }))
    .filter((e) => matches(e.slug));
  if (entries.length > 0)
    sections.push({ title: section.title, intro: section.intro, entries });
}
const bundled = new Set(
  sections.flatMap((s) => s.entries.map((e) => `${e.slug}.md`)),
);

// Build into a scratch dir and swap it in at the end, so a failed run
// never leaves a half-written docs/ behind.
const finalDir = path.join(packageDir, "docs");
if (existsSync(finalDir)) {
  const readme = path.join(finalDir, "README.md");
  if (!existsSync(readme) || !readFileSync(readme, "utf8").includes(MARKER)) {
    console.error(
      `bundle-package-docs: ${finalDir} exists and was not generated by this script; refusing to replace it`,
    );
    process.exit(1);
  }
}
const outDir = path.join(packageDir, ".docs-bundle.tmp");
rmSync(outDir, { recursive: true, force: true });

const pkgRef = `${pkg.name}@${pkg.version}`;
const index = [];
let totalBytes = 0;

for (const section of sections) {
  const items = [];
  for (const entry of section.entries) {
    const raw = readFileSync(path.join(SITE_DIR, entry.source), "utf8");
    const { data, content } = matter(raw);
    const title = entry.title || data.title || entry.slug;
    const description = data.description || "";
    const file = `${entry.slug}.md`;
    const fileDir = path.posix.dirname(file);

    let body = mdxToMarkdown(content, {
      source: entry.source,
      siteUrl: SITE_URL,
      pageUrl: entry.url,
      resolveLink: (href) => {
        const r = resolveDocHref(entry.source, href, entry.url);
        if (r.kind === "external") return r.href;
        if (r.kind === "doc" && bundled.has(r.file.replace(/\.mdx$/, ".md"))) {
          const rel = path.posix.relative(fileDir, r.file);
          return `${rel.startsWith(".") ? rel : `./${rel}`}${r.hash}`;
        }
        return `${SITE_URL}${r.url}${r.hash}`;
      },
    });
    if (!/^# /m.test(body.split("\n").slice(0, 5).join("\n"))) {
      body = `# ${title}\n\n${body}`;
    }

    const header = [
      "---",
      `title: ${JSON.stringify(title)}`,
      description && `description: ${JSON.stringify(description)}`,
      `online: ${JSON.stringify(SITE_URL + entry.url)}`,
      `package: ${JSON.stringify(pkgRef)}`,
      "---",
      "",
    ]
      .filter((l) => l !== "")
      .join("\n");

    const text = `${header}\n\n${body}`;
    const dest = path.join(outDir, file);
    mkdirSync(path.dirname(dest), { recursive: true });
    writeFileSync(dest, text);
    totalBytes += Buffer.byteLength(text);
    items.push(
      `- [${title}](./${file})${description ? `: ${description}` : ""}`,
    );
  }
  index.push(`## ${section.title}`, "");
  if (section.intro) index.push(section.intro, "");
  index.push(...items, "");
}

const readme = [
  `# ${pkg.name} documentation`,
  "",
  MARKER,
  "",
  `Offline copy of the LoraDB documentation for **${pkgRef}**. It describes`,
  "the version installed next to it, which can differ from the latest docs",
  `on ${SITE_URL}/docs. Links to pages that are not bundled here point to`,
  "the website.",
  "",
  `Everything else (other language bindings, the HTTP server, release notes)`,
  `lives at ${SITE_URL}/docs and ${SITE_URL}/llms.txt.`,
  "",
  ...index,
].join("\n");
writeFileSync(path.join(outDir, "README.md"), readme.replace(/\n+$/, "\n"));
totalBytes += Buffer.byteLength(readme);

rmSync(finalDir, { recursive: true, force: true });
renameSync(outDir, finalDir);

console.log(
  `bundle-package-docs: wrote ${bundled.size} pages + README.md to ${path.relative(ROOT, finalDir)}/ (${(totalBytes / 1024).toFixed(0)} KiB)`,
);
