// Build-time output for persisted operations: a manifest the server loads
// without parsing or validating, and TypeScript types for each
// operation's variables and result.
//
// Statement text is not in the manifest: it depends on variable values
// (a `where` present or null, cursors, limits) and on the request's
// claims, so it is compiled per request and cached (see the compile
// cache). What the manifest fixes is the document and its validation.

import {
  getNamedType,
  isEnumType,
  isInputObjectType,
  isInterfaceType,
  isListType,
  isNonNullType,
  isObjectType,
  isScalarType,
  isUnionType,
  Kind,
  parse,
  printSchema,
  lexicographicSortSchema,
  specifiedRules,
  typeFromAST,
  validate,
  visit,
  type DocumentNode,
  type FragmentDefinitionNode,
  type GraphQLCompositeType,
  type GraphQLInputType,
  type GraphQLNamedType,
  type GraphQLOutputType,
  type GraphQLSchema,
  type OperationDefinitionNode,
  type SelectionSetNode,
  type ValidationRule,
} from "graphql";
import { sha256 } from "./compile/hmac.js";

export interface OperationManifest {
  version: 1;
  /** Hash of the public schema the operations were validated against. */
  schemaHash: string;
  operations: Record<string, ManifestOperation>;
}

export interface ManifestOperation {
  name: string | undefined;
  kind: "query" | "mutation" | "subscription";
  /** Root fields, by response key. */
  rootFields: string[];
  /** The validated document, as a GraphQL AST without locations. */
  document: DocumentNode;
}

/** Hash of the schema clients see: a manifest is valid for it only. */
export function schemaHash(schema: GraphQLSchema): string {
  const bytes = sha256(
    new TextEncoder().encode(printSchema(lexicographicSortSchema(schema))),
  );
  return Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
}

/**
 * Parse and validate persisted operations (id → source) into a manifest.
 * Throws with every problem at once.
 */
export function buildManifest(
  schema: GraphQLSchema,
  operations: Record<string, string>,
  rules: ValidationRule[] = [],
): OperationManifest {
  const out: Record<string, ManifestOperation> = {};
  const problems: string[] = [];
  for (const [id, source] of Object.entries(operations)) {
    let doc: DocumentNode;
    try {
      doc = parse(source, { noLocation: true });
    } catch (err) {
      problems.push(`${id}: ${(err as Error).message}`);
      continue;
    }
    const errors = validate(schema, doc, [...specifiedRules, ...rules]);
    if (errors.length > 0) {
      problems.push(`${id}: ${errors.map((e) => e.message).join("; ")}`);
      continue;
    }
    const ops = doc.definitions.filter(
      (d): d is OperationDefinitionNode => d.kind === Kind.OPERATION_DEFINITION,
    );
    if (ops.length !== 1) {
      problems.push(`${id}: a persisted operation holds exactly one operation`);
      continue;
    }
    const op = ops[0]!;
    out[id] = {
      name: op.name?.value,
      kind: op.operation,
      rootFields: op.selectionSet.selections.flatMap((s) =>
        s.kind === Kind.FIELD ? [s.alias?.value ?? s.name.value] : [],
      ),
      document: doc,
    };
  }
  if (problems.length > 0) {
    throw new Error(
      `invalid persisted operations:\n  ${problems.join("\n  ")}`,
    );
  }
  return { version: 1, schemaHash: schemaHash(schema), operations: out };
}

